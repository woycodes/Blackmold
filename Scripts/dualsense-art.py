import sys, xml.etree.ElementTree as ET
src, out = sys.argv[1], sys.argv[2]
ns = '{http://www.w3.org/2000/svg}'
root = ET.parse(src).getroot()
def tag(e): return e.tag.replace(ns, '')
def pathstr(e):
    t = tag(e)
    if t == 'path': return e.get('d')
    if t == 'circle':
        cx, cy, r = (float(e.get(k)) for k in ('cx','cy','r'))
        return f"O{cx},{cy},{r}"
    if t == 'rect':
        x, y, w, h = (float(e.get(k)) for k in ('x','y','width','height'))
        return f"M{x},{y}l{w},0l0,{h}l{-w},0Z"
named, loose = {}, []
for e in root:
    t = tag(e)
    if t == 'g':
        gid = e.get('id')
        kids = [k for k in e if tag(k) in ('path','circle','rect')]
        for k in kids:
            if k.get('id'): named[k.get('id')] = pathstr(k)
        if gid: named[gid] = ' '.join(pathstr(k) for k in kids if not k.get('id'))
    elif t in ('path','circle','rect'):
        if e.get('id') == '画板1': continue
        if e.get('id'): named[e.get('id')] = pathstr(e)
        else: loose.append(pathstr(e))
# Loose shapes in file order: cross, square, triangle, circle symbols.
named['symbol-cross'], named['symbol-square'], named['symbol-triangle'], named['symbol-circle'] = loose[:4]
# The dpad groups hold an outline and an arrow; split them.
for d in ('up','down','left','right'):
    g = [pathstr(k) for k in root if False]
for g in root:
    if tag(g) == 'g' and (g.get('id') or '').startswith('dpad-'):
        kids = list(g)
        named[g.get('id')] = pathstr(kids[0]); named[g.get('id') + '-arrow'] = pathstr(kids[1])
def camel(s):
    p = s.split('-'); return p[0] + ''.join(x.title() for x in p[1:])
lines = ["// Generated by Scripts/dualsense-art.py from design/dualsense.svg in",
"// github.com/daidr/dualsense-tester, MIT License, Copyright (c) 2023 Xuezhou Dai (daidr).",
"// The full notice is in THIRD_PARTY_NOTICES.md.",
"import SwiftUI", "",
"/// Outline drawing of a DualSense, in the SVG's own units.",
"enum DualSenseArt {",
"    static let size = CGSize(width: 1116.45, height: 891.37)"]
for k in sorted(named):
    if k in ('r3group','l3group','画板1'): continue
    lines.append(f'    static let {camel(k)} = SVGPath.parse("{named[k]}")')
lines.append("}")
open(out,'w').write('\n'.join(lines) + '\n')
print(sorted(camel(k) for k in named))
